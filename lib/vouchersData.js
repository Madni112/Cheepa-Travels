export function slugify(text) {
  if (!text) return '';
  return text
    .toString()
    .toLowerCase()
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^\w\-]+/g, '')
    .replace(/\-\-+/g, '-')
    .replace(/^-+/, '')
    .replace(/-+$/, '');
}

export function getAllVouchers() {
  let vouchers = initialVouchers.map((v, i) => {
    const idNum = parseInt(v.id || (i + 1)) || (i + 1);
    const ub = v.ubNumber || v.voucherRefNo || `UB-${String(idNum).padStart(4, '0')}`;
    return {
      ...v,
      ubNumber: ub,
      voucherRefNo: ub,
    };
  });
  if (typeof window !== 'undefined') {
    const overrides = localStorage.getItem('voucher_overrides');
    const customVouchers = localStorage.getItem('custom_vouchers');
    
    let overrideMap = {};
    if (overrides) {
      try {
        overrideMap = JSON.parse(overrides);
      } catch (e) {}
    }

    // Apply overrides to initial vouchers
    vouchers = vouchers.map(v => {
      const key = v.slug || v.id;
      if (overrideMap[key] || overrideMap[v.id]) {
        return { ...v, ...(overrideMap[key] || overrideMap[v.id]) };
      }
      return v;
    });

    if (customVouchers) {
      try {
        const parsed = JSON.parse(customVouchers);
        const customList = parsed.map(v => {
          const key = v.slug || v.id;
          if (overrideMap[key] || overrideMap[v.id]) {
            return { ...v, ...(overrideMap[key] || overrideMap[v.id]) };
          }
          return v;
        });
        vouchers = [...vouchers, ...customList];
      } catch (e) {
        console.error('Error parsing custom vouchers', e);
      }
    }
  }
  return vouchers;
}

export function getVoucherBySlug(slugOrId) {
  if (!slugOrId) return null;
  const all = getAllVouchers();
  const normalized = decodeURIComponent(slugOrId).toLowerCase().trim().replace(/^(party:|party-)/, '');
  const cleanNorm = normalized.replace(/-(mr|mrs|miss|dr)$/, '').replace(/[^a-z0-9]/g, '');
  
  return all.find((v) => {
    if (!v) return false;
    const vSlug = (v.slug || '').toLowerCase();
    const vPartySlug = slugify(v.party || '').toLowerCase();
    const vSheetSlug = slugify(v.sheetName || '').toLowerCase();
    const vId = (v.id || '').toString().toLowerCase();

    if (vSlug === normalized || vId === normalized || vPartySlug === normalized || vSheetSlug === normalized) {
      return true;
    }

    const cleanVSlug = vSlug.replace(/-(mr|mrs|miss|dr)$/, '').replace(/[^a-z0-9]/g, '');
    const cleanVParty = vPartySlug.replace(/-(mr|mrs|miss|dr)$/, '').replace(/[^a-z0-9]/g, '');
    if (cleanNorm && (cleanVSlug.includes(cleanNorm) || cleanNorm.includes(cleanVSlug) || cleanVParty.includes(cleanNorm) || cleanNorm.includes(cleanVParty))) {
      return true;
    }

    return false;
  });
}

export async function fetchSupabaseVouchers() {
  try {
    const { data, error } = await supabase.from('vouchers').select('*').order('created_at', { ascending: true });
    if (!error && data && data.length > 0) {
      return data.map(mapSupabaseToVoucher);
    }
  } catch (err) {
    console.warn('Supabase fetch error:', err);
  }
  return getAllVouchers();
}

export async function fetchSupabaseVoucherBySlug(slugOrId) {
  if (!slugOrId) return null;
  const normalized = decodeURIComponent(slugOrId).toLowerCase().trim();
  try {
    const { data, error } = await supabase
      .from('vouchers')
      .select('*')
      .or(`slug.eq.${normalized},id.eq.${normalized}`)
      .single();
    if (!error && data) {
      return mapSupabaseToVoucher(data);
    }
  } catch (err) {}

  return getVoucherBySlug(slugOrId);
}

export function updateVoucher(slugOrId, updatedData) {
  const key = slugOrId || updatedData.slug || updatedData.id;
  if (typeof window !== 'undefined') {
    const overridesRaw = localStorage.getItem('voucher_overrides');
    let overrideMap = {};
    if (overridesRaw) {
      try {
        overrideMap = JSON.parse(overridesRaw);
      } catch (e) {}
    }
    overrideMap[key] = { ...updatedData };
    if (updatedData.slug) overrideMap[updatedData.slug] = { ...updatedData };
    if (updatedData.id) overrideMap[updatedData.id] = { ...updatedData };
    localStorage.setItem('voucher_overrides', JSON.stringify(overrideMap));
  }

  // Asynchronously sync to Supabase
  try {
    const row = mapVoucherToSupabase(updatedData);
    supabase.from('vouchers').upsert(row, { onConflict: 'id' }).then(({ error }) => {
      if (error) console.warn('Supabase update sync warning:', error);
    });
  } catch (e) {}

  return updatedData;
}

export function saveCustomVoucher(voucher) {
  const newVoucher = {
    ...voucher,
    id: voucher.id || 'custom-' + Date.now(),
    slug: voucher.slug || slugify(voucher.party) || 'voucher-' + Date.now(),
  };

  if (typeof window !== 'undefined') {
    const customVouchers = localStorage.getItem('custom_vouchers');
    let list = [];
    if (customVouchers) {
      try {
        list = JSON.parse(customVouchers);
      } catch (e) {}
    }
    list.push(newVoucher);
    localStorage.setItem('custom_vouchers', JSON.stringify(list));
  }

  // Asynchronously insert into Supabase
  try {
    const row = mapVoucherToSupabase(newVoucher);
    supabase.from('vouchers').insert(row).then(({ error }) => {
      if (error) console.warn('Supabase insert sync warning:', error);
    });
  } catch (e) {}

  return newVoucher;
}

